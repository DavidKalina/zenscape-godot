#!/usr/bin/env python3
"""The flight glyphs' polygon data, from the design's json to the script the
game loads: docs/design/ui/mock/glyphs.json -> scripts/endless/near_glyph_data.gd
(an export leaves docs/ out, so the game can't read the json itself).

    python tools/glyph_data.py            write the .gd
    python tools/glyph_data.py --check    exit 1 if the .gd is not what the json gives

Each polygon is kept as its tone (0 lit, 1 mid, 2 shade) and its points as an
SVG `points` string on the 24-unit grid, which is what scripts/endless/
near_glyphs.gd rasterises. The colours a glyph is drawn in are near_glyphs.gd's
(TINTS); this file carries only the json's grounds and kind tints.
"""
import json
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SOURCE = "docs/design/ui/mock/glyphs.json"
OUT = "scripts/endless/near_glyph_data.gd"


def num(x):
    return ("%.2f" % x).rstrip("0").rstrip(".")


def gd_str(s):
    return json.dumps(s, ensure_ascii=False)


def build():
    with open(os.path.join(ROOT, SOURCE), encoding="utf-8") as f:
        data = json.load(f)
    tones = data["tones"]
    out = []
    out.append("extends RefCounted")
    out.append("## GENERATED by tools/glyph_data.py from %s. Don't edit: change the" % SOURCE)
    out.append("## json and run `python tools/glyph_data.py`. The flight glyphs as flat polygons")
    out.append("## on a %d-unit grid (x right, y down), drawn in order, later over earlier:" % data["grid"])
    out.append("## [tone, \"x,y x,y ...\"], tone %s. Read by" % ", ".join("%d %s" % (i, t) for i, t in enumerate(tones)))
    out.append("## scripts/endless/near_glyphs.gd.")
    out.append("")
    out.append("const GRID := %.1f" % float(data["grid"]))
    out.append("## A ground's colours: lit, mid, shade, and the plate it sits on.")
    out.append("const GROUNDS := {")
    for name, g in data["grounds"].items():
        out.append("\t%s:[%s]," % (gd_str(name), ",".join(gd_str(g[k].lstrip("#")) for k in tones + ["on"])))
    out.append("}")
    out.append("const KIND_TINTS := {%s}" % ",".join("%s:%s" % (gd_str(k), gd_str(v.lstrip("#"))) for k, v in data["kind_tints"].items()))
    out.append("const ORDER := [%s]" % ",".join(gd_str(i) for i in data["order"]))
    out.append("const GLYPHS := {")
    count = 0
    for id in data["order"]:
        g = data["glyphs"][id]
        polys = []
        for p in g["polys"]:
            tone = int(p["tone"])
            if not 0 <= tone < len(tones) or len(p["points"]) < 3:
                raise SystemExit("glyph %s: a polygon with tone %r and %d points" % (id, p["tone"], len(p["points"])))
            polys.append("[%d,%s]" % (tone, gd_str(" ".join("%s,%s" % (num(x), num(y)) for x, y in p["points"]))))
            count += 1
        out.append("\t%s:{\"name\":%s,\"group\":%s,\"maps\":%s,\"polys\":[\n\t\t%s]}," % (
            gd_str(id), gd_str(g["name"]), gd_str(g["group"]), gd_str(g["maps"]), ",\n\t\t".join(polys)))
    out.append("}")
    return "\n".join(out) + "\n", len(data["order"]), count


def main():
    text, glyphs, polys = build()
    path = os.path.join(ROOT, OUT)
    if "--check" in sys.argv[1:]:
        old = open(path, encoding="utf-8").read() if os.path.exists(path) else ""
        if old != text:
            print("STALE %s: run python tools/glyph_data.py" % OUT)
            return 1
        print("OK %s is the json's (%d glyphs, %d polygons)" % (OUT, glyphs, polys))
        return 0
    with open(path, "w", encoding="utf-8", newline="\n") as f:
        f.write(text)
    print("wrote %s: %d glyphs, %d polygons, %d bytes" % (OUT, glyphs, polys, len(text.encode("utf-8"))))
    return 0


if __name__ == "__main__":
    sys.exit(main())
